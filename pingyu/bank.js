// 句库形状校验：称呼、结尾是非空字符串数组；维度里默认的五维 25 个标签都在，且每个标签值是非空字符串数组（多出来的标签不管）。
const isStrList = (v) => Array.isArray(v) && v.length > 0 && v.every((x) => typeof x === "string" && x.trim() !== "");
export function isValidBank(b) {
  if (!b || typeof b !== "object" || Array.isArray(b)) return false;
  if (!isStrList(b.称呼) || !isStrList(b.结尾)) return false;
  const dims = b.维度;
  if (!dims || typeof dims !== "object" || Array.isArray(dims)) return false;
  for (const d of DIMS) {
    const dim = dims[d];
    if (!dim || typeof dim !== "object" || Array.isArray(dim)) return false;
    for (const t of TAGS[d]) if (!isStrList(dim[t])) return false;
    for (const v of Object.values(dim)) if (!isStrList(v)) return false;
  }
  return true;
}
